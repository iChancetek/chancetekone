export const buildContextualPrompt = (context?: AgentContextPayload): string => {
  if (!context) return SYSTEM_PROMPT_BREAK_BEATS_AI;

  let memorySnippet = '';

  // 1. SHORT-TERM WORKING MEMORY
  const stm = context.shortTermMemory;
  memorySnippet += '\n\n### ⚡ Short-Term Working Memory (Active Session):';
  if (context.currentPath || stm?.activePath) {
    memorySnippet += `\n- Current Page Route: ${context.currentPath || stm?.activePath}`;
  }
  if (context.currentTrackTitle || stm?.activeTrackTitle) {
    memorySnippet += `\n- Currently Playing Track: "${context.currentTrackTitle || stm?.activeTrackTitle}" by ${context.currentArtistName || stm?.activeArtistName || 'Unknown'}`;
    if (context.currentBpm || stm?.activeBpm) {
      memorySnippet += ` (${context.currentBpm || stm?.activeBpm} BPM, ${context.currentGenre || stm?.activeGenre || 'Breakbeat'})`;
    }
  }
  if (context.currentVideoId || stm?.activeVideoId) {
    memorySnippet += `\n- Active Viewed Video ID: ${context.currentVideoId || stm?.activeVideoId}`;
  }
  if (context.currentAudiobookId || stm?.activeAudiobookId) {
    memorySnippet += `\n- Active Viewed Audiobook ID: ${context.currentAudiobookId || stm?.activeAudiobookId}`;
  }
  if (stm?.sessionWorkingNotes && stm.sessionWorkingNotes.length > 0) {
    memorySnippet += `\n- Session Working Scratchpad: ${stm.sessionWorkingNotes.join('; ')}`;
  }
  if (stm?.recentQueries && stm.recentQueries.length > 0) {
    memorySnippet += `\n- Recent Queries in Session: ${stm.recentQueries.join(', ')}`;
  }

  // 2. LONG-TERM PERSISTENT MEMORY
  const ltm = context.longTermMemory;
  if (ltm) {
    memorySnippet += '\n\n### 🧠 Long-Term Memory (User Musical DNA & Saved Facts):';
    if (ltm.userName || context.userName) {
      memorySnippet += `\n- User Name: ${ltm.userName || context.userName}`;
    }
    if (ltm.tasteProfile) {
      const tp = ltm.tasteProfile;
      if (tp.favoriteGenres?.length) {
        memorySnippet += `\n- Preferred Genres: ${tp.favoriteGenres.join(', ')}`;
      }
      if (tp.bpmSweetSpot) {
        memorySnippet += `\n- BPM Sweet Spot: ${tp.bpmSweetSpot.min} - ${tp.bpmSweetSpot.max} BPM (Ideal: ${tp.bpmSweetSpot.preferred || 95} BPM)`;
      }
      if (tp.eraPreferences?.length) {
        memorySnippet += `\n- Era Affinities: ${tp.eraPreferences.join(', ')}`;
      }
      if (tp.gearInterests?.length) {
        memorySnippet += `\n- Gear & Hardware Interests: ${tp.gearInterests.join(', ')}`;
      }
      if (tp.vibeTags?.length) {
        memorySnippet += `\n- Vibe & Texture Preferences: ${tp.vibeTags.join(', ')}`;
      }
    }

    if (ltm.explicitFacts && ltm.explicitFacts.length > 0) {
      memorySnippet += '\n- Explicit Remembered Facts:';
      ltm.explicitFacts.forEach((fact) => {
        memorySnippet += `\n  - [${fact.category.toUpperCase()}] ${fact.fact}`;
      });
    }
  }

  // 3. LANGUAGE PREFERENCE
  if (context.language === 'es') {
    memorySnippet += '\n\n### 🇪🇸 Language Requirement:\n- The user has selected **Spanish (Español)** as their active language. Respond in fluent, engaging, culturally authentic Spanish while preserving brand names and technical terms (8 OF SPADES WORKS, Break Beats AI, SP-1200, MPC60).';
  }

  return `${SYSTEM_PROMPT_BREAK_BEATS_AI}${memorySnippet}`;
};
