export const getRandomCoverArt = (): string => {
  const item = COVER_ART_CATALOG[Math.floor(Math.random() * COVER_ART_CATALOG.length)];
  return item.url;
};

export const getCoverArtsByCategory = (category: string): CoverArtItem[] => {
  if (category === 'all') return COVER_ART_CATALOG;
  return COVER_ART_CATALOG.filter((item) => item.category === category);
};
